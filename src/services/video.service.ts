interface ChannelProfile {
  _id: string;
  name: string;
  avatar: string;
  subscriberCount: number;
}

interface UploadVideoPayload {
  videoFile: {
    url: string;
    publicId: string;
  };
  duration: number;
  thumbnail: string;
  title: string;
  description: string;
  category: string;
  tags: string[];
  visibility: VideoVisibility;
}
interface VideoResult {
  video: {
    id: string;
    title: string;
    description: string;
    thumbnail: string;
    duration: number;
    tags: Array<string>;
    createdAt: Date;
    stats: {
      views: number;
      likesCount: number;
      commentsCount: number;
    };
    channel: ChannelProfile;
  };
  isSubscribed: boolean;
}

// Metadata Payload
interface MetadataPayload {
  title: string;
  description: string;
  category: string;
  tags: string[];
  playlist: string;
  visibility: string;
}

// Get home feed videos service
export const getFeedService = async (page: number, limit: number) => {
  // Calculate offset pagination
  const skip = (page - 1) * limit;

  // fetch all the videos available on the platform
  const [videos, totalVideos] = await videoRepository.findFeed(skip, limit);

  // Calculate Total Pages for pagination
  const totalPages = Math.ceil(totalVideos / limit);
  // return the videos including pagination
  return {
    videos,
    pagination: {
      page,
      limit,
      totalVideos,
      totalPages,
      hasNextPage: page < totalPages,
    },
  };
};

// Get single video service
export const getSingleVideoService = async (
  // get the id's
  videoId: string,
  viewerId?: string
): Promise<VideoResult> => {
  // get the video from cache first
  let videoData: VideoResult["video"] | null = await getCached(
    `video-details:${videoId}`
  );

  if (!videoData) {
    // find the video which is ready and visible and populate channel with it
    const video = await videoRepository.findVideoWithChannelInfo(videoId);
    // check if the video exists or not
    if (!video) {
      throw new ApiError(404, "Video Not Found!");
    }

    videoData = {
      id: video._id.toString(),
      title: video.title,
      description: video.description,
      thumbnail: video.thumbnail?.url ?? "",
      duration: video.duration,
      tags: video.tags,
      createdAt: video.createdAt,
      stats: {
        views: video.views,
        likesCount: video.likesCount,
        commentsCount: video.commentsCount,
      },
      channel: {
        _id: video.channel._id.toString(),
        name: video.channel.name,
        avatar: video.channel.avatar,
        subscriberCount: video.channel.subscriberCount,
      },
    };

    // set the new data to the cache
    await setCached(`video-details:${videoId}`, videoData, 300);
  }

  // check if the viewer subscribed to this channel or not
  let isSubscribed = false;

  if (viewerId) {
    const subscriptionExists = !!(await Subscription.exists({
      channel: videoData.channel._id,
      subscriber: viewerId,
    }));

    isSubscribed = subscriptionExists;
  }

  return {
    video: videoData,
    isSubscribed,
  };
};


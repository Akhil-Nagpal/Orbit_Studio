// Get upload signature service
export const getUploadSignatureService = async () => {
  // This signature is generated by Cloudinary SDK
  const timestamp = Math.round(Date.now() / 1000);

  const paramsToSign = {
    timestamp,
    folder: Bun.env.CLOUDINARY_FOLDER,
    resource_type: "videos",
  };

  const signature = cloudinary.utils.api_sign_request(
    paramsToSign,
    Bun.env.CLOUDINARY_API_SECRET as string
  );

  return {
    timestamp,
    signature,
    apiKey: Bun.env.CLOUDINARY_API_KEY,
    cloudName: Bun.env.CLOUDINARY_CLOUD_NAME,
    folder: Bun.env.CLOUDINARY_FOLDER,
  };
};

// create Video record / upload video
export const uploadVideoService = async (
  channelId: string,
  payload: UploadVideoPayload
) => {
  // check if the payload are valid or not
  if (!payload.videoFile.url || !payload.videoFile.publicId) {
    throw new ApiError(400, "Invalid Video File Payload");
  }
  // check all the required fields
  if (!payload.duration || payload.duration === 0) {
    throw new ApiError(400, "Invalid duration");
  }

  if (!payload.title || payload.title.trim() === "") {
    throw new ApiError(400, "Title is required");
  }

  // check if the thumbnail is valid or not
  const validThumbnail = generateThumbnails(
    payload.videoFile.publicId,
    payload.duration
  );

  if (!payload.thumbnail || !validThumbnail.includes(payload.thumbnail)) {
    throw new ApiError(400, "Invalid thumbnail");
  }
  // create the video record in DB but keep the metadata empty
  const createVideoRecord = await videoRepository.createVideo({
    channel: channelId,
    videoFile: {
      url: payload.videoFile.url,
      publicId: payload.videoFile.publicId,
    },
    duration: payload.duration,
    title: payload.title,
    description: payload.description || "",
    category: payload.category,
    tags: payload.tags || [],
    visibility: payload.visibility || VideoVisibility.PRIVATE,
    views: 0,
    likesCount: 0,
    commentsCount: 0,
  });
  // return the video
  return createVideoRecord;
};

// Update Metadata Service
export const updateMetadataService = async (
  // get the video and channel Id
  videoId: string,
  channelId: string,
  { title, description, category, tags, playlist, visibility }: MetadataPayload
) => {
  // find the video
  const video = await videoRepository.findVideoByChannel(videoId, channelId);
  // check if video exists or
  if (!video) {
    throw new ApiError(404, "Video Not Found!");
  }
  // update the video metadata and save the video
  await videoRepository.updateVideoMetadata(video, {
    title,
    description,
    category,
    tags,
    playlist: new Types.ObjectId(playlist),
    visibility: visibility as VideoVisibility,
  });

  // after updating metadata, invalidate Single video
  await invalidateCache(`video-details:${videoId}`);

  // return the updated video
  return video;
};

